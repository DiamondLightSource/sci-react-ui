import { OPACITY, SLOTS, THRESHOLDS, TOKEN_PREFIX } from "../palette.mjs";
import { channel, tokenName } from "./format.mjs";

export const buildCss = () => {
  const block = (mode, selector, extra = "") =>
    `${selector} {\n${SLOTS.map(
      (s, i) => `  ${tokenName(i)}: ${s[mode]}; /* ${s.name} */`,
    ).join("\n")}\n\n${SLOTS.map(
      (s, i) => `  ${tokenName(i)}-channel: ${channel(s[mode])};`,
    ).join("\n")}\n${extra}}\n`;
  const opacity = `\n  /* Fill opacities: rgb(var(${tokenName(0)}-channel) / var(${TOKEN_PREFIX}-fill-area)) */\n${Object.entries(
    OPACITY,
  )
    .map(([k, v]) => `  ${TOKEN_PREFIX}-fill-${k}: ${v};`)
    .join("\n")}\n`;
  return [
    "/* Generated by tools/chart-palette/build.mjs from palette.mjs. Do not edit by hand. */",
    [
      "/*",
      "   Draw charts on --ds-surface or --ds-background",
      `   (the colours are checked for ${THRESHOLDS.contrast}:1 contrast on both)`,
      "   and use series in order, --ds-chart-1 first.",
      "",
      `   Slots 1-${THRESHOLDS.coreSlots} are the core and stay separable under`,
      `   colour-vision deficiency; ${THRESHOLDS.coreSlots + 1}-${SLOTS.length} are additional.`,
      "*/",
    ].join("\n") + "\n",
    "/* Categorical chart palette, light mode */",
    block("light", ':root,\n[data-mode="light"]', opacity),
    "/* Categorical chart palette, dark mode */",
    block("dark", '[data-mode="dark"]'),
  ].join("\n");
};
