import { CVD_TYPES, hexToRgb, simulatedHex } from "../calc/colour.mjs";
import { MODES } from "../calc/validate.mjs";
import { HALO_WIDTH } from "../markers.mjs";
import { LINE, OPACITY, SLOTS, THRESHOLDS } from "../palette.mjs";
import { channel, tokenName } from "./format.mjs";

const simulated = (hex) =>
  Object.fromEntries(CVD_TYPES.map((v) => [v, simulatedHex(hex, v)]));

export const buildJson = (report) =>
  JSON.stringify(
    {
      description: `Categorical chart palette, ${SLOTS.length} slots, light and dark. Generated by build.mjs.`,
      surfaces: Object.fromEntries(
        MODES.map((m) => [m, report.modes[m].surfaces]),
      ),
      fillOpacity: OPACITY,
      thresholds: {
        contrast: THRESHOLDS.contrast,
        contrastFloor: THRESHOLDS.contrastFloor,
        textContrast: THRESHOLDS.textContrast,
        coreSlots: THRESHOLDS.coreSlots,
      },
      secondChannel: {
        minLineWidth: LINE.width,
        minMarkerSize: LINE.marker,
        markerHalo: HALO_WIDTH,
      },
      slots: SLOTS.map((s, i) => ({
        slot: i + 1,
        name: s.name,
        token: tokenName(i),
        marker: s.marker,
        ...Object.fromEntries(
          MODES.map((m) => [
            m,
            {
              hex: s[m],
              rgb: hexToRgb(s[m]),
              channel: channel(s[m]),
              simulated: simulated(s[m]),
            },
          ]),
        ),
      })),
      nearStatus: report.nearStatus.map((n) => ({
        slot: n.slot,
        name: n.name,
        token: n.token,
        deltaE: Math.round(n.deltaE * 10) / 10,
      })),
      weakPairs: report.weakPairs.map((w) => ({
        slots: [w.a, w.b],
        names: [SLOTS[w.a - 1].name, SLOTS[w.b - 1].name],
      })),
    },
    null,
    2,
  ) + "\n";
